integer_num = 10            # Integer data type
float_num = 10.5            # Float data type
complex_num = 3 + 4j        # Complex data type
boolean_num = True          # Boolean data type

# Display the values and their data types
print("Integer:", integer_num)
print("Type:", type(integer_num))

print("\nFloat:", float_num)
print("Type:", type(float_num))

print("\nComplex:", complex_num)
print("Type:", type(complex_num))

print("\nBoolean:", boolean_num)
print("Type:", type(boolean_num))